#!/usr/bin/env python3
"""Exhaustive check of the QRC Gate 1 rank-selection theorem for the source law S_pre^NR.

Source law (schema qrc.spre.nested_reciprocity_activity.v1), as defined in the QRC
repository file docs/QRC_SPRE_AUTHORITATIVE_NESTED_RECIPROCITY_SOURCE_AND_COORDINATE_FREE_
GATE1_THEOREM.md, Sections 1 to 3:

  An object is (D, M): D is a finite set of n primitive excitation types, P2(D) is the set
  of all 2-element subsets of D, and M is a partial matching between D and P2(D) that is
  injective on both sides and transverse: (d, p) in M implies d not in p. With m = |M|,

      S = lam1 * (n - m) + lam2 * (C(n,2) - m) - h * n.

  Equal costs lam1 = lam2 = lam give the reciprocal law S_pre^NR (eq. 2.4); unequal
  positive costs are the generalisation of Theorem 3.4.

Claims checked:
  A  For 0 < h < 2*lam2 the global minimiser over all configurations of all ranks is
     unique: n = 3 with the complement matching d -> D minus {d}.
  B  The excitation gap is g = min(3h, 2*lam - h) (eq. 3.6); for unequal costs it is
     g12 = min(3h, lam1 + 2h, lam1 + lam2, 2*lam2 - h) (eq. 3.14).
  C  Lemma 3.1: the largest transverse matching has size 0 for n = 0, 1, 2 and n for n >= 3.
  D  At h = 0 the zero-temperature groupoid probabilities are Pr(n=3) = 1/7, Pr(n=0) = 6/7
     (eq. 3.18), using groupoid weight 1/|Aut| per isomorphism class.

Method. Ranks n <= N_ENUM are enumerated exhaustively: every labelled configuration is
generated by backtracking and its action is computed in exact rational arithmetic. The
enumerator's counts are cross-checked against an independently coded bitmask dynamic
programme. Ranks n > N_ENUM are covered by the bound m <= min(n, C(n,k)) (the left
projection of M is injective), which gives S >= lam2*n*(n-3)/2 - h*n for binary spans.
The script checks that this bound lies above the ground energy for every n up to
N_BOUND and that its increment lam2*(n-1) - h is positive at N_BOUND. Because that
increment grows with n, the bound then holds for every larger n; this monotonicity is
the only analytic step not executed numerically.

Every claim is also run on deliberately wrong inputs (h outside the window, wrong
energies, a wrong gap formula, a wrong weighting, a buggy enumerator) and must FAIL there.
Exit status 0 if and only if every observed outcome equals its expectation.

Not checked here: the all-rank Gibbs concentration bound (eq. 3.9), the endpoint group,
volume, heat kernel and co-metric (see check_gate_results.py for the last four).

Run: python3 -I -B check_gate1_selection.py
"""

from __future__ import annotations

import sys
import time
from collections import Counter
from fractions import Fraction as Fr
from itertools import combinations, permutations
from math import comb, factorial

N_ENUM = 6        # exhaustive enumeration for the reciprocal law
N_ENUM_VAR = 5    # exhaustive enumeration for the deliberately wrong variants (they are larger)
N_BOUND = 400     # explicit lower-bound check for N_ENUM < n <= N_BOUND
N_MATCH = 12      # maximum transverse matching computed by augmenting paths up to this rank

RESULTS: list[tuple[str, bool, bool]] = []


def record(name: str, observed: bool, expected: bool) -> None:
    RESULTS.append((name, observed, expected))
    tag = "PASS" if observed else "FAIL"
    exp = "PASS" if expected else "FAIL"
    ok = "ok" if observed == expected else "MISMATCH"
    print(f"  [{ok}] {name}: observed {tag}, expected {exp}")


# ---------------------------------------------------------------------------
# State space
# ---------------------------------------------------------------------------

def spans(n: int, k: int = 2) -> list[tuple[int, ...]]:
    return list(combinations(range(n), k))


def allowed(n: int, k: int = 2, transverse: bool = True) -> tuple[list, list[list[int]]]:
    sp = spans(n, k)
    return sp, [[i for i, p in enumerate(sp) if (not transverse) or (d not in p)] for d in range(n)]


def enumerate_configs(n: int, k: int = 2, transverse: bool = True, span_injective: bool = True):
    """Yield every labelled configuration as a tuple: entry d is the matched span index or None."""
    _, allow = allowed(n, k, transverse)
    match: list[int | None] = [None] * n

    def rec(d: int, used: int):
        if d == n:
            yield tuple(match)
            return
        match[d] = None
        yield from rec(d + 1, used)
        for i in allow[d]:
            if span_injective and (used >> i) & 1:
                continue
            match[d] = i
            yield from rec(d + 1, used | (1 << i))
        match[d] = None

    yield from rec(0, 0)


def count_by_m(n: int, **variant) -> Counter:
    c: Counter = Counter()
    for cfg in enumerate_configs(n, **variant):
        c[sum(x is not None for x in cfg)] += 1
    return c


def dp_counts(n: int) -> Counter:
    """Independent count of transverse, two-sided injective matchings by size.

    Pairs are bitmasks over D; transversality is 'bit d of the pair is clear'. Dynamic
    programme over the elements of D with the set of used pairs as state.
    """
    pair_masks = [(1 << a) | (1 << b) for a in range(n) for b in range(a + 1, n)]
    ways = {0: 1}
    for d in range(n):
        new: dict[int, int] = {}
        for used, w in ways.items():
            new[used] = new.get(used, 0) + w          # d unmatched
            for j, pm in enumerate(pair_masks):
                if pm >> d & 1 or used >> j & 1:
                    continue
                nu = used | (1 << j)
                new[nu] = new.get(nu, 0) + w
        ways = new
    out: Counter = Counter()
    for used, w in ways.items():
        out[bin(used).count("1")] += w
    return out


def max_transverse_matching(n: int, k: int = 2, transverse: bool = True) -> int:
    """Maximum bipartite matching (augmenting paths); does not use the cyclic construction."""
    sp, allow = allowed(n, k, transverse)
    owner = [-1] * len(sp)

    def augment(d: int, seen: list[bool]) -> bool:
        for i in allow[d]:
            if not seen[i]:
                seen[i] = True
                if owner[i] == -1 or augment(owner[i], seen):
                    owner[i] = d
                    return True
        return False

    return sum(augment(d, [False] * len(sp)) for d in range(n))


def automorphisms(n: int, cfg: tuple, k: int = 2) -> int:
    sp = spans(n, k)
    index = {p: i for i, p in enumerate(sp)}
    count = 0
    for s in permutations(range(n)):
        ok = True
        for d in range(n):
            img = None if cfg[d] is None else index[tuple(sorted(s[x] for x in sp[cfg[d]]))]
            if cfg[s[d]] != img:
                ok = False
                break
        count += ok
    return count


def is_complement_matching(n: int, cfg: tuple) -> bool:
    if n != 3:
        return False
    sp = spans(3)
    return all(cfg[d] is not None and set(sp[cfg[d]]) == {0, 1, 2} - {d} for d in range(3))


# ---------------------------------------------------------------------------
# Energy and global minimisation
# ---------------------------------------------------------------------------

def action(n: int, m: int, lam1: Fr, lam2: Fr, h: Fr, k: int = 2) -> Fr:
    return lam1 * (n - m) + lam2 * (comb(n, k) - m) - h * n


COUNT_CACHE: dict[tuple, dict[int, Counter]] = {}


def counts_for(n_enum: int, k: int, transverse: bool, span_injective: bool) -> dict[int, Counter]:
    key = (n_enum, k, transverse, span_injective)
    if key not in COUNT_CACHE:
        COUNT_CACHE[key] = {n: count_by_m(n, k=k, transverse=transverse, span_injective=span_injective)
                            for n in range(n_enum + 1)}
    return COUNT_CACHE[key]


def analyse(lam1, lam2, h, k=2, transverse=True, span_injective=True, n_enum=N_ENUM) -> dict:
    lam1, lam2, h = Fr(lam1), Fr(lam2), Fr(h)
    counts = counts_for(n_enum, k, transverse, span_injective)
    levels = []  # (energy, n, m, labelled count)
    for n, c in counts.items():
        for m, cnt in c.items():
            levels.append((action(n, m, lam1, lam2, h, k), n, m, cnt))
    ground = min(e for e, *_ in levels)
    ground_levels = [(n, m, cnt) for e, n, m, cnt in levels if e == ground]
    excited = [e for e, *_ in levels if e > ground]
    excited_min = min(excited) if excited else None
    # tail lower bound for n_enum < n <= N_BOUND
    lb = {n: action(n, min(n, comb(n, k)), lam1, lam2, h, k) for n in range(n_enum + 1, N_BOUND + 1)}
    tail_min = min(lb.values())
    tail_above = all(v > ground for v in lb.values())
    tail_increasing_at_end = lb[N_BOUND] - lb[N_BOUND - 1] > 0
    gap = None
    if excited_min is not None:
        gap = min(excited_min, tail_min) - ground
    # labelled ground configurations (only materialised when they are few)
    ground_cfgs = []
    if sum(cnt for _, _, cnt in ground_levels) <= 50:
        for n, m, _ in ground_levels:
            for cfg in enumerate_configs(n, k=k, transverse=transverse, span_injective=span_injective):
                if sum(x is not None for x in cfg) == m:
                    ground_cfgs.append((n, cfg))
    return {"ground": ground, "ground_levels": ground_levels, "gap": gap, "tail_above": tail_above,
            "tail_increasing_at_end": tail_increasing_at_end, "ground_cfgs": ground_cfgs}


def claim_A(res: dict) -> bool:
    """Unique global minimiser: rank three with the complement matching, nothing below in the tail."""
    if not (res["tail_above"] and res["tail_increasing_at_end"]):
        return False
    if [(n, m) for n, m, _ in res["ground_levels"]] != [(3, 3)]:
        return False
    cfgs = res["ground_cfgs"]
    return len(cfgs) == 1 and is_complement_matching(*cfgs[0])


def g_equal(lam, h):
    lam, h = Fr(lam), Fr(h)
    return min(3 * h, 2 * lam - h)


def g_unequal(lam1, lam2, h):
    lam1, lam2, h = Fr(lam1), Fr(lam2), Fr(h)
    return min(3 * h, lam1 + 2 * h, lam1 + lam2, 2 * lam2 - h)


def fmt(x) -> str:
    return str(x) if isinstance(x, Fr) and x.denominator != 1 else str(int(x)) if x is not None else "None"


# ---------------------------------------------------------------------------
# Checks
# ---------------------------------------------------------------------------

def main() -> int:
    t0 = time.time()

    print("0. State-space enumeration (binary spans, transverse, injective on both sides)")
    base = counts_for(N_ENUM, 2, True, True)
    for n, c in base.items():
        print(f"     n={n}: {sum(c.values()):>7} labelled configurations; by m: {dict(sorted(c.items()))}")
    dp = {n: dp_counts(n) for n in range(N_ENUM + 1)}
    record(f"enumerator counts equal independent DP counts for n=0..{N_ENUM}",
           all(base[n] == dp[n] for n in base), True)
    mutant = counts_for(N_ENUM_VAR, 2, True, False)
    record(f"[wrong input] enumerator without span-side injectivity equals DP for n=0..{N_ENUM_VAR}",
           all(mutant[n] == dp[n] for n in mutant), False)

    print("\nC. Lemma 3.1: maximum transverse matching size")
    mm = [max(m for m, c in base[n].items() if c) for n in range(N_ENUM + 1)]
    mm += [max_transverse_matching(n) for n in range(N_ENUM + 1, N_MATCH + 1)]
    claim = [0, 0, 0] + list(range(3, N_MATCH + 1))
    print(f"     observed max m for n=0..{N_MATCH}: {mm}")
    record(f"max m = 0 for n<=2 and n for 3<=n<={N_MATCH}", mm == claim, True)
    dmin = [comb(n, 2) + n - 2 * mm[n] for n in range(N_MATCH + 1)]
    record("Delta_min(n) = 0,1,3 then n(n-3)/2", dmin == [0, 1, 3] + [n * (n - 3) // 2 for n in range(3, N_MATCH + 1)], True)
    record("[wrong input] Delta_min(2) = 1 (a transverse match at rank two)", dmin[2] == 1, False)
    mm_nt = [max_transverse_matching(n, transverse=False) for n in range(N_MATCH + 1)]
    record("[wrong input] without transversality max m = 0 for n<=2", mm_nt[:3] == [0, 0, 0], False)

    print("\nA, B. Unique rank-three ground state and gap, equal costs (S_pre^NR), 0 < h < 2 lam")
    equal_params = [(1, Fr(1, 10)), (1, Fr(1, 2)), (1, 1), (1, Fr(19, 10)), (Fr(5, 2), Fr(3, 10)), (Fr(7, 10), Fr(13, 10))]
    for lam, h in equal_params:
        r = analyse(lam, lam, h)
        aut = automorphisms(*r["ground_cfgs"][0]) if len(r["ground_cfgs"]) == 1 else None
        print(f"     lam={fmt(Fr(lam))}, h={fmt(Fr(h))}: ground {fmt(r['ground'])} at (n,m)="
              f"{[(n, m) for n, m, _ in r['ground_levels']]}, |Aut|={aut}, gap {fmt(r['gap'])}, claim {fmt(g_equal(lam, h))}")
        record(f"lam={fmt(Fr(lam))} h={fmt(Fr(h))}: unique minimiser is n=3 complement matching", claim_A(r), True)
        record(f"lam={fmt(Fr(lam))} h={fmt(Fr(h))}: gap = min(3h, 2lam-h)", r["gap"] == g_equal(lam, h), True)
        record(f"lam={fmt(Fr(lam))} h={fmt(Fr(h))}: ground object has |Aut| = 6", aut == 6, True)

    print("\n   Deliberately wrong inputs (each must FAIL claim A)")
    for lam, h, why in [(1, 2, "h = 2 lam (upper boundary)"), (1, Fr(5, 2), "h > 2 lam"),
                        (1, 0, "h = 0 (lower boundary)"), (1, Fr(-1, 2), "h < 0")]:
        r = analyse(lam, lam, h)
        print(f"     {why}: ground {fmt(r['ground'])} at (n,m)={[(n, m) for n, m, _ in r['ground_levels']]}")
        record(f"[wrong input] {why}: unique minimiser is n=3 complement matching", claim_A(r), False)
    r = analyse(1, 1, Fr(1, 2), transverse=False, n_enum=N_ENUM_VAR)
    print(f"     no transversality: ground at {[(n, m, c) for n, m, c in r['ground_levels']]} (n, m, labelled count)")
    record("[wrong energy] transversality dropped: unique complement-matching minimiser", claim_A(r), False)
    r = analyse(1, 1, Fr(1, 2), k=3, n_enum=N_ENUM_VAR)
    print(f"     ternary spans: ground at (n,m)={[(n, m) for n, m, _ in r['ground_levels']]}")
    record("[wrong energy] ternary spans (k=3): rank three selected", claim_A(r), False)
    r = analyse(1, 0, Fr(1, 2))
    print(f"     no unmatched-span cost (lam2=0): enumerated ground at {[(n, m) for n, m, _ in r['ground_levels']]},"
          f" tail increasing: {r['tail_increasing_at_end']}")
    record("[wrong energy] lam2 = 0: rank three selected", claim_A(r), False)
    r = analyse(1, 1, 1)
    record("[wrong formula] gap = min(3h, 2lam) at lam=1, h=1", r["gap"] == min(Fr(3), Fr(2)), False)

    print("\nA, B. Unequal positive costs (Theorem 3.4), 0 < h < 2 lam2")
    unequal_params = [(1, 2, Fr(7, 2)), (3, 1, Fr(3, 2)), (Fr(1, 5), 1, Fr(19, 10)), (2, Fr(1, 2), Fr(1, 4)),
                      (Fr(1, 10), Fr(3, 2), 1)]
    for l1, l2, h in unequal_params:
        r = analyse(l1, l2, h)
        print(f"     lam1={fmt(Fr(l1))}, lam2={fmt(Fr(l2))}, h={fmt(Fr(h))}: gap {fmt(r['gap'])}, claim {fmt(g_unequal(l1, l2, h))}")
        tag = f"lam1={fmt(Fr(l1))} lam2={fmt(Fr(l2))} h={fmt(Fr(h))}"
        record(f"{tag}: unique minimiser is n=3 complement matching", claim_A(r), True)
        record(f"{tag}: gap = g12", r["gap"] == g_unequal(l1, l2, h), True)
    r = analyse(2, Fr(1, 2), Fr(3, 2))
    record("[wrong input] window set by lam1: lam1=2 lam2=1/2 h=3/2 selects rank three", claim_A(r), False)
    r = analyse(Fr(1, 10), Fr(3, 2), 1)
    wrong = min(Fr(3), Fr(1, 10) + 2, 2 * Fr(3, 2) - 1)
    record("[wrong formula] g12 without the lam1+lam2 term at lam1=1/10 lam2=3/2 h=1", r["gap"] == wrong, False)

    print("\nD. Activation boundary h = 0: groupoid zero-temperature probabilities")
    r = analyse(1, 1, 0)
    lv = {n: cnt for n, m, cnt in r["ground_levels"]}
    print(f"     ground energy {fmt(r['ground'])}; labelled ground counts by rank: {lv}")
    w_groupoid = {n: Fr(cnt, factorial(n)) for n, cnt in lv.items()}
    z = sum(w_groupoid.values())
    p3 = w_groupoid.get(3, Fr(0)) / z
    print(f"     Pr(n=3) = {p3}, Pr(n=0) = {w_groupoid.get(0, Fr(0)) / z}")
    record("ground ranks at h=0 are exactly {0, 3}", sorted(lv) == [0, 3] and r["tail_above"], True)
    record("Pr(n=3) = 1/7 with groupoid weights 1/n! per labelled object", p3 == Fr(1, 7), True)
    w_lab = {n: Fr(cnt) for n, cnt in lv.items()}
    record("[wrong weighting] labelled weights give Pr(n=3) = 1/7",
           w_lab.get(3, Fr(0)) / sum(w_lab.values()) == Fr(1, 7), False)

    mismatches = [x for x in RESULTS if x[1] != x[2]]
    print(f"\nSummary: {len(RESULTS)} checks, {len(mismatches)} mismatches with expectation "
          f"({time.time() - t0:.1f} s)")
    return 1 if mismatches else 0


if __name__ == "__main__":
    sys.exit(main())
